export interface AcpxPromptArgs {
  session_id: string;
  prompt: string;
  wait: boolean;
  timeout_ms: number;
  max_output_chars: number;
}

export async function acpxPrompt(args: AcpxPromptArgs): Promise<ServerResult> {
  const record = lookupSession(args.session_id);
  if (!record) return errorResult(`Unknown session_id: ${args.session_id}`);

  let cwd: string;
  try {
    cwd = await validateAcpxCwd(record.cwd);
  } catch (error) {
    return errorResult(`Session cwd is no longer valid: ${message(error)}`);
  }
  if (cwd !== record.cwd) {
    return errorResult(`Session scope mismatch for ${args.session_id}`);
  }

  let acpxSessionId: string;
  try {
    acpxSessionId = requireAcpxSessionName(record);
  } catch (error) {
    return errorResult(`Session cannot be resolved safely: ${message(error)}`);
  }

  const argv = [
    ...buildGlobalArgv(cwd, args.timeout_ms),
    record.agent, 'prompt',
    '--session', acpxSessionId,
    ...(args.wait === false ? ['--no-wait'] : []),
    '--', args.prompt,
  ];

  let proc: TypedProcessResult;
  try {
    proc = await runAcpx(argv, cwd, args.timeout_ms, args.max_output_chars);
  } catch (error) {
    return errorResult(`Failed to run acpx: ${message(error)}`);
  }

  const ndjson = parseNdjson(proc.stdout);
  const assistantText = extractAssistantText(ndjson.events);
  const finalResult = extractFinalResult(ndjson.events);
  const rpcError = extractRpcError(ndjson.events);

  record.lastSeenAt = Date.now();

  return jsonResult({
    session_id: record.sessionId,
    agent: record.agent,
    cwd: record.cwd,
    exit_code: proc.exitCode,
    signal: proc.signal,
    timed_out: proc.timedOut,
    stdout_truncated: proc.stdoutTruncated,
    stderr_truncated: proc.stderrTruncated,
    stdout_is_json: ndjson.allLinesValidJson,
    assistant_text: assistantText.length > 0 ? assistantText : undefined,
    result: finalResult,
    error: rpcError,
    stdout: proc.stdout,
    stderr: proc.stderr,
  });
}

