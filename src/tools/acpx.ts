// acpx_cancel
// ---------------------------------------------------------------------------

export interface AcpxCancelArgs {
  session_id: string;
}

export async function acpxCancel(args: AcpxCancelArgs): Promise<ServerResult> {
  const record = lookupSession(args.session_id);
  if (!record) return errorResult(`Unknown session_id: ${args.session_id}`);

  let cwd: string;
  try {
    cwd = await validateAcpxCwd(record.cwd);
  } catch (error) {
    return errorResult(`Session cwd is no longer valid: ${message(error)}`);
  }
  if (cwd !== record.cwd) {
    return errorResult(`Session scope mismatch for ${args.session_id}`);
  }

  let acpxSessionId: string;
  try {
    acpxSessionId = requireAcpxSessionName(record);
  } catch (error) {
    return errorResult(`Session cannot be resolved safely: ${message(error)}`);
  }

  const argv = [...buildGlobalArgv(cwd, LOCAL_OP_TIMEOUT_MS), record.agent, 'cancel', '--session', acpxSessionId];

  let proc: TypedProcessResult;
  try {
    proc = await runAcpx(argv, cwd, LOCAL_OP_TIMEOUT_MS, LOCAL_OP_MAX_OUTPUT_CHARS);
  } catch (error) {
    return jsonResult({ session_id: record.sessionId, status: 'failed', reason: `Failed to run acpx: ${message(error)}` });
  }

  if (proc.timedOut) {
    return jsonResult({ session_id: record.sessionId, status: 'failed', reason: 'cancel command timed out' });
  }
  if (proc.exitCode !== 0) {
    return jsonResult({
      session_id: record.sessionId,
      status: 'failed',
      exit_code: proc.exitCode,
      stderr: proc.stderr,
      stdout: proc.stdout,
    });
  }

  const parsed = tryParseJson(proc.stdout);
  let status: 'accepted' | 'no_active_prompt' | 'failed' = 'failed';
  if (parsed.ok && typeof parsed.value?.cancelled === 'boolean') {
    status = parsed.value.cancelled ? 'accepted' : 'no_active_prompt';
  }

  return jsonResult({
    session_id: record.sessionId,
    status,
    raw: parsed.ok ? parsed.value : proc.stdout,
  });
}
