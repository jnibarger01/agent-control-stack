import { build } from "esbuild";
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const entryPoint = resolve(root, "apps/chatgpt-widget/src/main.tsx");
const output = resolve(root, "apps/gateway/src/chatgpt-dashboard-widget.generated.ts");
const result = await build({
  entryPoints: [entryPoint],
  bundle: true,
  format: "iife",
  minify: true,
  platform: "browser",
  target: "es2022",
  write: false
});
const javascript = result.outputFiles.find((file) => file.path.endsWith(".js"))?.text;
const stylesheet = result.outputFiles.find((file) => file.path.endsWith(".css"))?.text ?? "";
if (!javascript) throw new Error("chatgpt widget bundle did not produce JavaScript");
const html = `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>ACS Control Center</title><style>${stylesheet}</style></head><body><div id="root"></div><script>${javascript}</script></body></html>`;
await mkdir(dirname(output), { recursive: true });
await writeFile(output, `// Generated by scripts/build-chatgpt-widget.mjs. Do not edit.\nexport const chatgptDashboardWidgetHtml = ${JSON.stringify(html)};\n`);
